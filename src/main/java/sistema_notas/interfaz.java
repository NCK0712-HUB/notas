    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = campo_nombre.getText().trim();
        String codigo = campo_codigo.getText().trim();

        if (nombre.isEmpty() || codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debes escribir el nombre y el código del estudiante.");
            (nombre.isEmpty() ? campo_nombre : campo_codigo).requestFocus();
            return;
        }

        // Cada nota se valida (número y rango 0.0 - 5.0); si falla se muestra el aviso y se detiene
        BigDecimal nota1 = leerNota(campo_nota1, "primera");
        if (nota1 == null) {
            return;
        }
        BigDecimal nota2 = leerNota(campo_nota2, "segunda");
        if (nota2 == null) {
            return;
        }
        BigDecimal nota3 = leerNota(campo_nota3, "tercera");
        if (nota3 == null) {
            return;
        }

        // Definitiva = 30 % + 30 % + 40 % 
        BigDecimal parte1 = nota1.multiply(PORCENTAJE_NOTA1);   
        BigDecimal parte2 = nota2.multiply(PORCENTAJE_NOTA2);   
        BigDecimal parte3 = nota3.multiply(PORCENTAJE_NOTA3);   

        BigDecimal definitiva = parte1.add(parte2).add(parte3);
        definitiva = definitiva.setScale(2, RoundingMode.HALF_UP); 

        String estado;
        if (definitiva.compareTo(NOTA_APROBATORIA) >= 0) {
            estado = "Aprobado";
        } else {
            estado = "Reprobado";
        }

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.addRow(new Object[]{
            codigo, nombre,
            nota1.toPlainString(), nota2.toPlainString(), nota3.toPlainString(),
            definitiva.toPlainString(), estado
        });

        limpiarCampos();
    }//GEN-LAST:event_jButton1ActionPerformed

